"use client";

import { useState } from "react";
import { useApi } from "@/components/useApi";
import { useDashboard } from "@/components/DashboardProvider";
import {
  RiskBadge,
  StatusBadge,
  Loading,
  ErrorBox,
  SectionTitle,
  relativeTime,
} from "@/components/ui";
import { IconShield, IconCheck, IconClose } from "@/components/icons";
import type { AlertRow } from "@/components/types";

export default function ThreatsPage() {
  const [status, setStatus] = useState("open");
  const [severity, setSeverity] = useState("all");
  const { triggerRefresh } = useDashboard();

  const url = `/api/alerts?status=${status}&severity=${severity}&limit=50`;
  const { data, loading, error } = useApi<{ rows: AlertRow[]; total: number }>(
    url,
  );

  async function update(id: string, newStatus: "reviewed" | "dismissed") {
    const res = await fetch(`/api/alerts/${id}/status`, {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ status: newStatus }),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error ?? "Could not update alert.");
    triggerRefresh();
  }

  return (
    <div className="space-y-5">
      <SectionTitle
        title="Threat Detection"
        subtitle="Security alerts generated by rule-based heuristics and the ML anomaly engine"
      />

      <div className="panel panel-pad flex flex-wrap items-center gap-3">
        <div className="flex items-center gap-1 rounded-lg border border-white/10 bg-white/[0.03] p-1">
          {["open", "reviewed", "dismissed", "all"].map((s) => (
            <button
              key={s}
              onClick={() => setStatus(s)}
              className={`rounded-md px-3 py-1.5 text-sm capitalize transition ${
                status === s
                  ? "bg-sky-500/15 text-sky-300"
                  : "text-slate-400 hover:text-slate-200"
              }`}
            >
              {s}
            </button>
          ))}
        </div>
        <div className="flex items-center gap-1 rounded-lg border border-white/10 bg-white/[0.03] p-1">
          {["all", "high", "medium", "low"].map((s) => (
            <button
              key={s}
              onClick={() => setSeverity(s)}
              className={`rounded-md px-3 py-1.5 text-sm capitalize transition ${
                severity === s
                  ? "bg-sky-500/15 text-sky-300"
                  : "text-slate-400 hover:text-slate-200"
              }`}
            >
              {s}
            </button>
          ))}
        </div>
        <div className="ml-auto text-xs text-slate-400">
          {data?.total ?? 0} alerts
        </div>
      </div>

      {loading && <Loading label="Loading alerts…" />}
      {error && <ErrorBox message={error} />}

      {!loading && !error && (
        <div className="space-y-3">
          {data?.rows.length === 0 && (
            <div className="panel panel-pad text-center text-sm text-slate-400">
              No alerts in this view.
            </div>
          )}
          {data?.rows.map((a) => (
            <div
              key={a.id}
              className="panel panel-pad animate-fade-up flex flex-wrap items-start gap-4"
            >
              <div className="grid h-11 w-11 shrink-0 place-items-center rounded-xl bg-rose-500/10 text-rose-300">
                <IconShield />
              </div>
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-center gap-2">
                  <RiskBadge level={a.severity} />
                  <span className="chip bg-white/5 text-slate-300 capitalize">
                    {a.alertType.replace(/_/g, " ")}
                  </span>
                  <StatusBadge status={a.status} />
                  <span className="text-xs text-slate-500">
                    {relativeTime(a.createdAt)}
                  </span>
                </div>
                <p className="mt-2 text-sm leading-snug text-slate-200">
                  {a.description}
                </p>
                <p className="mt-1 text-xs text-slate-500">
                  User: {a.username ?? "—"}
                  {a.ipAddress ? ` · IP ${a.ipAddress}` : ""}
                  {a.riskScore != null ? ` · risk ${a.riskScore}` : ""}
                </p>
              </div>
              {a.status === "open" && (
                <div className="flex shrink-0 gap-2">
                  <button
                    className="btn btn-ghost"
                    onClick={() => update(a.id, "reviewed")}
                  >
                    <IconCheck width={16} height={16} />
                    Review
                  </button>
                  <button
                    className="btn btn-danger"
                    onClick={() => update(a.id, "dismissed")}
                  >
                    <IconClose width={16} height={16} />
                    Dismiss
                  </button>
                </div>
              )}
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
